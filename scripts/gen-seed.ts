/**
 * npm run gen:seed — generate supabase/seed.sql from data/seed.ts
 * (via buildSeedRows) so SQL and in-app seed can never drift.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { buildSeedRows } from "../lib/seed-rows";

function esc(s: string): string {
  return s.replace(/'/g, "''");
}

function lit(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (Array.isArray(v)) {
    // Postgres text[] literal
    const inner = v
      .map((x) => `"${String(x).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`)
      .join(",");
    return `'${esc(`{${inner}}`)}'`;
  }
  if (typeof v === "object") {
    return `'${esc(JSON.stringify(v))}'::jsonb`;
  }
  return `'${esc(String(v))}'`;
}

function main() {
  const { policies, claims, notes, appeals } = buildSeedRows();

  const lines: string[] = [
    "-- AUTO-GENERATED by npm run gen:seed — DO NOT EDIT BY HAND",
    "-- Source of truth: data/seed.ts + data/cached-appeals.ts via lib/seed-rows.ts",
    "",
    "truncate table appeals, patient_ehr_notes, denied_claims, payer_policies cascade;",
    "",
  ];

  for (const p of policies) {
    lines.push(
      `insert into payer_policies (id, payer, policy_code, title, body) values (${lit(p.id)}, ${lit(p.payer)}, ${lit(p.policy_code)}, ${lit(p.title)}, ${lit(p.body)});`,
    );
  }
  lines.push("");

  for (const c of claims) {
    lines.push(
      `insert into denied_claims (id, patient_alias, cpt_codes, billed_amount, payer_name, plan_type, carc_code, rarc_code, denial_reason, denied_at, status, policy_id) values (${lit(c.id)}, ${lit(c.patient_alias)}, ${lit(c.cpt_codes)}, ${lit(c.billed_amount)}, ${lit(c.payer_name)}, ${lit(c.plan_type)}, ${lit(c.carc_code)}, ${lit(c.rarc_code)}, ${lit(c.denial_reason)}, ${lit(c.denied_at)}, ${lit(c.status)}, ${lit(c.policy_id)});`,
    );
  }
  lines.push("");

  for (const n of notes) {
    lines.push(
      `insert into patient_ehr_notes (id, claim_id, note_type, authored_at, text) values (${lit(n.id)}, ${lit(n.claim_id)}, ${lit(n.note_type)}, ${lit(n.authored_at)}, ${lit(n.text)});`,
    );
  }
  lines.push("");

  for (const a of appeals) {
    lines.push(
      `insert into appeals (id, claim_id, analysis, letter, p2p, model, latency_ms, created_at, is_cached, is_active) values (${lit(a.id)}, ${lit(a.claim_id)}, ${lit(a.analysis)}, ${lit(a.letter)}, ${lit(a.p2p)}, ${lit(a.model)}, ${lit(a.latency_ms)}, ${lit(a.created_at)}, ${lit(a.is_cached)}, ${lit(a.is_active)});`,
    );
  }
  lines.push("");

  const out = resolve(__dirname, "../supabase/seed.sql");
  writeFileSync(out, lines.join("\n"), "utf8");
  console.log(`Wrote ${out} (${policies.length} policies, ${claims.length} claims, ${notes.length} notes, ${appeals.length} appeals)`);
}

main();
